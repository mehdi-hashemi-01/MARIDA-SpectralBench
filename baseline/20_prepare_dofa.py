"""v0.6 / step 20: verify pretrained DOFA and cache 11-band dense features.

Needs internet ON FIRST RUN (DOFA official GitHub code and
~448 MB real checkpoint). Requires CUDA; reads only official TRAIN and VAL.
NO TEST READS OR MODEL TRAINING HERE. Saves features locally; do not Git commit.
"""
import json
import time
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from settings import BANDS
from unet_core import (get_split_paths, training_statistics,
                       MaridaSegmentationDataset, seed_everything)
from dofa_transfer import (cache_config, CACHE_ROOT, META_FILE, WAVELENGTH_UM,
                           feature_path, check_cached_feature, save_cache_metadata,
                           verify_cache_metadata, load_real_pretrained_dofa,
                           dofa_dense_tokens, EMBED_DIM, PATCH_GRID)

# ----------------- PYCHARM SETTINGS -----------------
BATCH_SIZE = 2      # Use 1 if RTX 5070 Laptop GPU runs out of VRAM.
NUM_WORKERS = 0     # Recommended for Windows PyCharm.
# -----------------------------------------------------

if not torch.cuda.is_available():
    raise RuntimeError("CUDA not available. Run 15_check_gpu_and_data.py first")
device = torch.device("cuda")
seed_everything(42)
print("GPU:", torch.cuda.get_device_name(0), "| torch:", torch.__version__)
print("Wavelength mapping (micrometres):")
print(dict(zip(BANDS, WAVELENGTH_UM)))

# Intentionally do NOT call get_all_split_paths() - we do not open TEST.
train_paths, train_names, lookup = get_split_paths("train")
val_paths, val_names, _ = get_split_paths("val", lookup)
if train_names & val_names:
    raise AssertionError("TRAIN and VAL filenames overlap")
means, stds, class_counts, class_weights, debris_flags = training_statistics(train_paths)
config = cache_config(means, stds, train_paths, val_paths)

# Never mix a cache from another model/statistics/manifest.
if META_FILE.is_file():
    meta = verify_cache_metadata(config)
else:
    meta = None

missing = {}
for split, paths in (("train", train_paths), ("val", val_paths)):
    missing[split] = []
    for path in paths:
        cached = feature_path(split, path)
        if cached.exists():
            check_cached_feature(cached)
        else:
            missing[split].append(path)
    print(f"{split}: {len(paths)} patches; {len(missing[split])} features to cache")

if missing["train"] or missing["val"]:
    model, checkpoint_sha = load_real_pretrained_dofa()
    if meta is not None and meta["checkpoint_sha256"] != checkpoint_sha:
        raise RuntimeError("Different DOFA checkpoint SHA256; stop instead of mixing caches")
    # Note: save meta only after successful verification of pretrained weights.
    if meta is None:
        meta = save_cache_metadata(config, checkpoint_sha)
    model = model.to(device).eval()
    started = time.perf_counter()
    for split, paths in missing.items():
        if not paths:
            continue
        dataset = MaridaSegmentationDataset(paths, means, stds, augment=False)
        loader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=False,
                            num_workers=NUM_WORKERS, pin_memory=True)
        for batch_idx, (x, y, conf, filenames) in enumerate(loader, 1):
            x = x.to(device, non_blocking=True)
            with torch.inference_mode(), torch.autocast("cuda", dtype=torch.float16):
                feat = dofa_dense_tokens(model, x)
            feat_np = feat.float().cpu().numpy().astype(np.float16)
            if not np.isfinite(feat_np).all():
                raise ValueError("Non-finite features generated by DOFA; stop and inspect preprocessing")
            for row, filename in zip(feat_np, filenames):
                target = feature_path(split, Path(filename))
                target.parent.mkdir(parents=True, exist_ok=True)
                temporary = target.with_suffix(".tmp.npy")
                np.save(temporary, row, allow_pickle=False)
                temporary.replace(target)
            if batch_idx % 25 == 0:
                print(f"{split}: {min(batch_idx * BATCH_SIZE, len(paths))}/{len(paths)} ",
                      "| elapsed seconds:", round(time.perf_counter() - started, 1))
    del model
    torch.cuda.empty_cache()

for split, paths in (("train", train_paths), ("val", val_paths)):
    for path in paths:
        check_cached_feature(feature_path(split, path))
print("\nPASS: real DOFA weights verified and all frozen features cached")
print("Train", len(train_paths), "| Val", len(val_paths), "| TEST not accessed")
print("Pretrained checkpoint SHA256:", meta["checkpoint_sha256"])
print("Cache location:", CACHE_ROOT)
print("Next: 21_train_dofa_head.py (training decoder only)")
